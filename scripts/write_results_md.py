"""Generate RESULTS.md from the files in results/ (never typed by hand).

Usage:  python scripts/write_results_md.py
Every number in RESULTS.md is read from a result file, and the command that produced that
file is printed next to it.
"""
from __future__ import annotations

import csv
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.dataset import load_all  # noqa: E402

PY = r".venv\Scripts\python"


def read_csv(p: Path) -> list[dict]:
    with open(p, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def pct(x) -> str:
    return f"{100 * float(x):.1f}%"


def main() -> int:
    res = ROOT / "results"
    clips = load_all()
    timing = sorted({c.timing_source for c in clips})
    measured = timing == ["mms_fa_auto"]
    wk_dir = res   # rows carry timing_source / seconds_status; seconds are estimates unless measured
    L = ["# RESULTS", "",
         f"Generated by `{PY} scripts/write_results_md.py` on {dt.date.today().isoformat()}. "
         "Do not edit by hand: re-run the commands below.", ""]

    # ---- status banner
    statuses = {c.clip_id: c.raw["status"] for c in clips}
    L += ["## Data status", "",
          "| clip | audio | transcript | translation | timing source |", "|---|---|---|---|---|"]
    for c in clips:
        s = statuses[c.clip_id]
        L.append(f"| {c.clip_id} | {s['audio']} | {s['transcript']} | {s['translation']} | {c.timing_source} |")
    L.append("")
    if not measured:
        L += ["> **No measured timing results yet.** The six recordings have not been made, so the",
              "> wait-k numbers below use `placeholder_estimate` timings (durations estimated from",
              "> character counts, `src/dataset.py`). They exercise the pipeline and are NOT measurements.",
              "> Word-based AL and the evidence-safe rates of the wait-k and EAW-lex policies depend only",
              "> on the transcripts and translations, not on timings; all second-based numbers and EAW-pause",
              "> depend on timings and must be recomputed after recording.", ""]

    # ---- audio QC
    qc = ROOT / "data" / "manifests" / "audio_qc.csv"
    L += ["## Audio quality checks", "", f"Command: `{PY} scripts/prepare_audio.py` -> `data/manifests/audio_qc.csv`", ""]
    if qc.exists():
        rows = read_csv(qc)
        L += ["| clip | duration (s) | RMS dBFS | peak dBFS | clipped | problems |", "|---|---|---|---|---|---|"]
        L += [f"| {r['clip_id']} | {r['duration_s']} | {r['rms_dbfs']} | {r['peak_dbfs']} | {r['clipped_fraction']} | {r['problems']} |" for r in rows]
    else:
        L.append("PENDING: no recordings.")
    L.append("")

    # ---- boundary audit
    bj = res / "boundary_audit_summary.json"
    L += ["## Thirty-boundary alignment audit", "",
          f"Commands: `{PY} scripts/run_alignment.py`, `{PY} scripts/audit_boundaries.py make-sheet`, "
          f"manual marking in Audacity, `{PY} scripts/audit_boundaries.py score` -> `results/boundary_audit.csv`", ""]
    if bj.exists():
        b = json.loads(bj.read_text(encoding="utf-8"))
        L += ["| metric | value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in b.items()]
    else:
        L.append("PENDING: requires recordings, automatic alignment and manual marking of 30 word onsets.")
    L.append("")

    # ---- checker
    cj = res / "checker_summary.json"
    L += ["## Entity checker accuracy (checker vs. hand labels)", "",
          f"Command: `{PY} scripts/evaluate_checker.py` -> `results/checker_summary.json`, `results/checker_eval.csv`", "",
          "Unit = one (translation variant, annotated entity) decision. Positive class = 'entity is wrong'. "
          "Gold labels were assigned by the author before running the checker; they are not independent annotations. "
          "This measures the checker, not any translation model.", ""]
    if cj.exists():
        s = json.loads(cj.read_text(encoding="utf-8"))
        L += ["| subset | decisions | accuracy | error precision | error recall | TP | FP | FN | TN |",
              "|---|---|---|---|---|---|---|---|---|"]

        def row(name, m):
            return (f"| {name} | {m['n']} | {pct(m['accuracy'])} | {pct(m['error_precision'])} | "
                    f"{pct(m['error_recall'])} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} |")
        L.append(row(f"all ({s['n_variants']} variants)", s["overall"]))
        L.append(row("non-hard variants", s["non_hard_variants"]))
        L.append(row("hard variants", s["hard_variants"]))
        for cat, m in s["by_category"].items():
            L.append(row(cat, m))
        L += ["", "Disagreements (checker vs. gold):", ""]
        L += [f"- {d['clip_id']}/{d['variant']}/{d['entity_id']}: gold={'correct' if d['gold_correct'] else 'wrong'}, "
              f"checker={'pass' if d['checker_pass'] else 'fail'} ({d['reason']})" for d in s["disagreements"]]
        ref = read_csv(res / "reference_check.csv")
        for mode in ("fluent", "literal"):
            rs = [r for r in ref if r["mode"] == mode]
            L.append(f"\nReference translations ({mode}): {sum(r['pass'] == 'True' for r in rs)}/{len(rs)} entities pass "
                     f"(`results/reference_check.csv`).")
    L.append("")

    # ---- wait-k
    agg_p = wk_dir / "metrics_aggregate.csv"
    L += ["## Wait-k / entity-aware waiting simulation", "",
          f"Command: `{PY} scripts/evaluate_waitk.py` -> `{agg_p.relative_to(ROOT).as_posix()}`, per-clip "
          f"`{(wk_dir / 'metrics.csv').relative_to(ROOT).as_posix()}`, plot "
          f"`{(wk_dir / 'latency_vs_entity_accuracy.png').relative_to(ROOT).as_posix()}`", "",
          f"Timing source: **{', '.join(timing)}**. English word duration: fixed 0.40 s (estimate). "
          "Latency columns are means over clips; entity columns are pooled over all annotated entities. "
          "`fixed text` = checker on the unmodified reference (identical for every policy by construction); "
          "`simulated` = ambiguity-sensitive stress test (entity replaced by its annotated premature guess "
          "if committed before its determining source word).", ""]
    if agg_p.exists():
        agg = read_csv(agg_p)
        L += ["| policy | AL (words) | AL decision (s) | AL speech onset (s) | first output (s) | end offset (s) | entities | evidence-safe | simulated acc. | fixed-text acc. |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for a in agg:
            L.append(f"| {a['policy']} | {float(a['AL_words']):.2f} | {float(a['AL_decision_s']):.2f} | "
                     f"{float(a['AL_onset_s']):.2f} | {float(a['first_output_s']):.2f} | {float(a['end_offset_s']):.2f} | "
                     f"{a['n_entities']} | {pct(a['evidence_safe_rate'])} | {pct(a['sim_entity_acc'])} | {pct(a['fixed_text_acc'])} |")
    L.append("")

    # ---- k sweep + operating point
    sp = wk_dir / "selected_operating_point.json"
    if sp.exists():
        so = json.loads(sp.read_text(encoding="utf-8"))
        p, sec = so["primary_words"], so["secondary_seconds_estimated"]
        L += ["### Wait-k sweep (k = 1..10) and operating-point selection", "",
              f"Command: `{PY} scripts/evaluate_waitk.py` -> `results/selected_operating_point.json`, "
              "`results/k_sensitivity.csv`, `results/k_sweep.png`, `results/pareto_frontier.png`", "",
              f"Rule: {so['selection_rule']}", "",
              f"- Accuracy metric: evidence-safe entity rate (equal to simulated entity accuracy for every policy: "
              f"{so['sim_equals_evidence_safe']}). Fixed-reference accuracy values across all policies: "
              f"{', '.join(pct(v) for v in so['fixed_text_acc_values'])} (identical by construction).",
              f"- Pareto-optimal k (AL in words): {p['pareto_k']}; dominated: {p['dominated_k']}.",
              f"- **Selected: wait-{p['selected']['k']}** — evidence-safe {pct(p['selected']['evidence_safe_rate'])}, "
              f"AL {p['selected']['AL_words']:.2f} source words; knee distance {p['knee_distance']} vs one-entity resolution "
              f"{p['one_entity_in_normalised_units']} → knee is {'**weak**' if p['knee_is_weak'] else 'clear'}.",
              "- Near-equivalent alternatives: " + "; ".join(
                  f"wait-{a['k']} ({pct(a['evidence_safe_rate'])}, AL {a['AL_words']:.2f})" for a in p["alternatives"]) + ".",
              f"- Versus wait-{p['vs_most_aggressive']['k']}: AL +{p['vs_most_aggressive']['latency_change']:.2f} source words, "
              f"evidence-safe +{p['vs_most_aggressive']['accuracy_change_points']:.1f} percentage points.",
              "- Utility sensitivity (alpha -> k, words): " + ", ".join(
                  f"{s['alpha']}→{s['selected_k']}" for s in p["utility_sensitivity"]) +
              f"; changes with alpha: {p['utility_selection_changes_with_alpha']}.",
              f"- Same rule on estimated seconds (AL of speech onsets, ESTIMATED): wait-{sec['selected']['k']}; alpha -> k: " +
              ", ".join(f"{s['alpha']}→{s['selected_k']}" for s in sec["utility_sensitivity"]) + ".",
              "- Reference policies that dominate wait-k points (words): " + "; ".join(
                  f"{d['policy']} dominates wait-{d['dominates_waitk']}" for d in so["reference_policies_dominating_waitk_words"]
                  if d["dominates_waitk"]) + ". On estimated seconds: " + (", ".join(
                  d["policy"] for d in so["reference_policies_dominating_waitk_seconds_estimated"] if d["dominates_waitk"]) or "none") + ".",
              ""]

    # ---- error analysis by category / entity
    et_p = wk_dir / "entity_timing.csv"
    if et_p.exists():
        et = read_csv(et_p)
        pols = ["wait-3", "wait-5", "wait-7", "EAW-lex k=3", "EAW-pause k=3", "sentence-by-sentence"]
        cats = sorted({e["category"] for e in et})
        L += ["### Error analysis: entities committed after their determining word, by category", "",
              f"Source: `{et_p.relative_to(ROOT).as_posix()}` (same command).", "",
              "| category | " + " | ".join(pols) + " |", "|---|" + "---|" * len(pols)]
        for c in cats:
            cells = []
            for p in pols:
                rs = [e for e in et if e["policy"] == p and e["category"] == c]
                cells.append(f"{sum(e['safe'] == 'True' for e in rs)}/{len(rs)}")
            L.append(f"| {c} | " + " | ".join(cells) + " |")
        for p in ("wait-3", "EAW-pause k=3"):
            bad = [e for e in et if e["policy"] == p and e["safe"] == "False"]
            L += ["", f"Unsafe under {p} (entity: Hindi words still missing at commit): " +
                  ", ".join(f"{e['entity_id']} ({e['words_short']})" for e in bad)]
        L.append("")

    # ---- Part A worked example
    L += ["## Part A appendix check", "",
          f"Command: `{PY} -m pytest tests/test_waitk.py -k part_a -q`", "",
          "मैंने कल अपना पुराना बैंक खाता बंद करवा दिया (|x| = 9) -> 'Yesterday I got my old bank account closed' (|y| = 8). "
          "wait-3: g = [3, 4, 5, 6, 7, 8, 9, 9], tau = 7, r = 8/9, AL = (42 - 21 x 9/8)/7 = **2.625 source words** "
          "(STACL Eq. 9).", ""]
    L += ["## Unit tests", "", f"Command: `{PY} -m pytest -q` (see FINAL_STATUS.md for the last recorded run).", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
